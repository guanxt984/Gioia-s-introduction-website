import assert from 'node:assert/strict';
import * as THREE from 'three';
import * as visibility from '../src/experience-island-visibility.js';
import * as zoom from '../src/experience-island-zoom.js';

assert.equal(typeof visibility.createIslandStabilizer, 'function', 'island changes need a stable candidate');
const stable = visibility.createIslandStabilizer(120);
assert.equal(stable('personal', 0), 'personal');
assert.equal(stable('school', 10), 'personal');
assert.equal(stable('school', 129), 'personal');
assert.equal(stable('personal', 130), 'personal');
assert.equal(stable('school', 140), 'personal');
assert.equal(stable('school', 259), 'personal');
assert.equal(stable('school', 260), 'school');
assert.equal(stable('internship', 270), 'school');
assert.equal(stable('personal', 380), 'school');
assert.equal(stable('personal', 500), 'personal');

const label = (key, category, depth, x = 100, y = 100) => ({key, category, depth, x, y, width: 50, height: 20});
const layout = visibility.layoutProjectLabels;
assert.equal(typeof layout, 'function');
let placed = layout([label('dim', 'school', -1), label('current', 'personal', -2)], 'personal', null, null);
assert.deepEqual(placed.map(p => p.key), ['current']);
placed = layout([label('far', 'school', -4), label('near', 'internship', -2)], 'personal', null, null);
assert.deepEqual(placed.map(p => p.key), ['near']);
placed = layout([label('a', 'personal', -2), label('b', 'personal', -3)], 'personal', null, null);
assert.equal(placed.length, 2, 'current labels are retained with a bounded offset');
assert.ok(Math.abs(placed[1].offsetY) <= 32);
assert.ok(Math.abs(placed[1].y - placed[0].y) >= 24);
placed = layout([label('current', 'personal', -1), label('selected', 'school', -3)], 'personal', 'selected', null);
assert.equal(placed[0].key, 'selected');
assert.equal(placed.length, 2);
placed = layout([label('current', 'personal', -1), label('hover', 'personal', -2)], 'personal', null, 'hover');
assert.equal(placed[0].key, 'hover');
placed = layout([label('near', 'personal', -1), label('hover', 'personal', -2)], 'personal', null, 'hover', new Map([['hover', -32]]));
assert.equal(placed.find(p => p.key === 'hover').offsetY, -32, 'hover must not move its own hit target');
placed = layout([label('near', 'personal', -1, 100, 100), label('hover', 'personal', -2, 100, 100)], 'personal', null, 'hover', new Map([['hover', { top: 68 }]]));
assert.equal(placed.find(p => p.key === 'hover').y, 68, 'hover keeps its previous screen position when priorities change');

assert.equal(typeof zoom.preserveOrbitDistance, 'function');
const camera = new THREE.PerspectiveCamera();
const target = new THREE.Vector3(1, 2, 3);
camera.position.set(4, 6, 3);
zoom.preserveOrbitDistance(camera, target, {minDistance: 4, maxDistance: 6});
assert.deepEqual(camera.position.toArray(), [4, 6, 3]);
zoom.preserveOrbitDistance(camera, target, {minDistance: 6, maxDistance: 9});
assert.ok(Math.abs(camera.position.distanceTo(target) - 6) < 1e-10);
assert.ok(camera.position.clone().sub(target).normalize().distanceTo(new THREE.Vector3(.6, .8, 0)) < 1e-10);
zoom.preserveOrbitDistance(camera, target, {minDistance: 2, maxDistance: 3});
assert.ok(Math.abs(camera.position.distanceTo(target) - 3) < 1e-10);
console.log('PASS: stable island transitions, collision priorities/bounded placement, resize distance and direction');
