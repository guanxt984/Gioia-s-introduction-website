import assert from 'node:assert/strict';
import { initSkillCloudElastic } from '../public/skillcloud-elastic.js';

const win = new EventTarget();
Object.assign(win, { scrollY: 0, innerHeight: 1000 });
globalThis.window = win;
const body = Object.assign(new EventTarget(), { scrollTop: 0, scrollHeight: 5000 });
const html = { scrollTop: 0, scrollHeight: 1000 };
const doc = new EventTarget();
let dialogOpen = false;
Object.assign(doc, { body, documentElement: html, scrollingElement: html, hidden: false, querySelector: selector => selector.includes('[open]') ? (dialogOpen ? {} : null) : {} });
globalThis.document = doc;
const reduced = Object.assign(new EventTarget(), { matches: false });
globalThis.matchMedia = () => reduced;
let intersect, mutation;
globalThis.IntersectionObserver = class { constructor(fn) { intersect = fn; } observe() {} disconnect() {} };
globalThis.MutationObserver = class { constructor(fn) { mutation = fn; } observe() {} disconnect() {} };
const callbacks = new Map();
let id = 0, time = 0;
globalThis.requestAnimationFrame = fn => { callbacks.set(++id, fn); return id; };
globalThis.cancelAnimationFrame = key => callbacks.delete(key);
const element = () => ({ style: { removeProperty(key) { delete this[key === 'will-change' ? 'willChange' : key]; } } });
const zones = Array.from({ length: 4 }, (_, i) => {
  const chips = Array.from({ length: i === 3 ? 6 : 4 }, element);
  return { ...element(), chips, querySelectorAll: () => chips };
});
const chips = zones.flatMap(zone => zone.chips);
const cleanup = initSkillCloudElastic({ querySelectorAll: () => zones });
const step = () => { time += 16.667; const pending = [...callbacks.values()]; callbacks.clear(); pending.forEach(fn => fn(time)); };
const scroll = delta => { body.scrollTop += delta; body.dispatchEvent(new Event('scroll')); step(); };
const offsets = () => zones.map(zone => parseFloat(zone.style.translate?.split(' ')[1] || 0));
intersect([{ isIntersecting: true }]);
scroll(100);
assert.ok(offsets().every(y => y > 0 && y <= 28), 'cloud motion stays within reduced 28px cap');
const chipOffsets = () => chips.map(chip => parseFloat(chip.style.translate?.split(' ')[1] || 0));
assert.equal(chips.length, 18);
assert.ok(chipOffsets().every(y => y > 0 && y <= 18), 'every label has subtle bounded motion');
assert.equal(new Set(chipOffsets()).size, chips.length, 'all 18 labels have distinct independent displacements');
assert.ok(Math.max(...chipOffsets()) - Math.min(...chipOffsets()) > 10, 'label offsets have a visible spread without increasing the 18px cap');
for (let i = 0; i < 20; i++) step();
assert.ok(Math.min(...chipOffsets()) < 0.5 && Math.max(...chipOffsets()) > 8, 'quick labels settle while slower labels continue trailing');
assert.ok(new Set(offsets()).size > 1, 'clouds have different response times');
for (let i = 0; i < 350; i++) step();
assert.deepEqual(offsets(), [0, 0, 0, 0], 'all clouds settle to their original layout');
assert.equal(callbacks.size, 0, 'animation stops when settled');
assert.ok(chipOffsets().every(y => y === 0), 'labels return to their original positions');
scroll(-100);
assert.ok(offsets().every(y => y < 0), 'upward scroll reverses the lag');
dialogOpen = true; mutation(); scroll(80);
assert.deepEqual(offsets(), [0, 0, 0, 0], 'detail reading stays stationary');
assert.ok(chipOffsets().every(y => y === 0), 'detail pauses labels too');
dialogOpen = false; mutation();
scroll(200);
assert.ok(offsets().every(y => y > 0 && y <= 28), 'cloud displacement stays bounded');
reduced.matches = true; reduced.dispatchEvent(new Event('change')); scroll(100);
assert.deepEqual(offsets(), [0, 0, 0, 0], 'reduced motion disables displacement');
reduced.matches = false; scroll(1000);
assert.deepEqual(offsets(), [0, 0, 0, 0], 'anchor jumps do not fling clouds');
intersect([{ isIntersecting: false }]); scroll(100);
assert.equal(callbacks.size, 0, 'offscreen animation stays idle');
cleanup(); scroll(100);
assert.equal(callbacks.size, 0, 'cleanup removes scroll handling');
console.log('PASS: reduced cloud lag, all 18 distinct label offsets, direction, settling, idle, dialog pause, reduced motion, anchor jumps, cleanup');
